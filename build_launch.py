#!/usr/bin/env python3
"""Build launch/ = the PUBLIC countdown-only page that Vercel serves (vercel.json at the repo root: outputDirectory "launch").
Only the countdown screen goes in: its HTML block from site/index.html, the countdown CSS rules from style.css, countdown.js,
the background loops + posters, logo, icons and fonts. No other site HTML/CSS/JS/photos.
Settings: LAUNCH_AT and LAUNCH_NOTE from site/config.js. null = "Launching soon — after Diwali" (no numbers).
Launch day: change vercel.json outputDirectory from "launch" to "site" (README: "Launch day").
Usage: python3 build_launch.py"""
import json, os, re, shutil
HERE = os.path.dirname(os.path.abspath(__file__)); SITE = HERE + "/site"; OUT = HERE + "/launch"
cfg = open(SITE + "/config.js", encoding="utf-8").read()
m = re.search(r'(?m)^\s*LAUNCH_AT:\s*(null|"[^"]*")', cfg); LAUNCH = json.loads(m.group(1))
m = re.search(r'(?m)^\s*LAUNCH_NOTE:\s*("(?:[^"\\]|\\.)*")', cfg); NOTE = json.loads(m.group(1)) if m else ""
idx = open(SITE + "/index.html", encoding="utf-8").read()
head = idx[:idx.index("</head>")]
head = re.sub(r'<link rel="stylesheet"[^>]*>', '<link rel="stylesheet" href="assets/launch.css?v=1">', head)
head = re.sub(r'<script src="config.js"></script>\s*<script src="assets/js/countdown.js[^"]*"></script>',
              '<script>window.PSQ_CONFIG={LAUNCH_AT:%s,LAUNCH_NOTE:%s};window.PSQ_LAUNCH_ONLY=true;</script>\n<script src="assets/countdown.js?v=1"></script>'
              % (json.dumps(LAUNCH), json.dumps(NOTE, ensure_ascii=False)), head)
assert "launch.css" in head and "assets/countdown.js" in head and "config.js" not in head, "index.html head changed: update build_launch.py"
s = idx.index('<div class="launch" id="launch"'); e = idx.index('<a class="skip"')
block = idx[s:e]
html = head + "</head>\n<body>\n" + block + "</body>\n</html>\n"
js = open(SITE + "/assets/js/countdown.js", encoding="utf-8").read()
subs = [(r'  if \(q\.has\("preview"\)\) return;[^\n]*\n', ''),
        (r'var raw = q\.get\("launch"\) \|\| C\.LAUNCH_AT \|\| null;', 'var raw = C.LAUNCH_AT || null;'),
        (r'if \(!soon && Date\.now\(\) >= target\) return;[^\n]*', 'if (!soon && Date.now() >= target) soon = true; // public countdown build: never blank'),
        (r'el\.classList\.add\("open"\); root\.classList\.add\("ln-reveal"\);', 'if (window.PSQ_LAUNCH_ONLY) { location.replace("/"); return; }\n            el.classList.add("open"); root.classList.add("ln-reveal");')]
for a, b in subs:
    js, n = re.subn(a, b, js); assert n == 1, "countdown.js changed: " + a
js = js.replace("?preview=1 = full site straight away.  ?launch=2026-11-15T10:00:00+05:30 = test the countdown with any date.", "Public countdown-only build (launch/).")
# CSS: keep only fonts, base reset and the countdown (.ln-*/.launch) rules
css = open(SITE + "/assets/css/style.css", encoding="utf-8").read()
def blocks(s):
    out = []; i = 0
    while True:
        j = s.find("{", i)
        if j < 0: break
        sel = re.sub(r"/\*.*?\*/", "", s[i:j], flags=re.S).strip(); d = 1; k = j + 1
        while d and k < len(s):
            d += {"{": 1, "}": -1}.get(s[k], 0); k += 1
        out.append((sel, s[j + 1:k - 1])); i = k
    return out
KEEP = {"@font-face", ":root", "*,*:before,*:after", "[hidden]", "html", "body", "img,video"}
def extract(s):
    out = []
    for sel, b in blocks(s):
        if sel.startswith("@media"):
            inner = extract(b)
            if inner.strip(): out.append(sel + "{" + inner + "}")
        elif sel in KEEP or "ln-" in sel or "launch" in sel or sel.startswith("@keyframes ln"): out.append(sel + "{" + b + "}")
    return "\n".join(out)
lcss = "/* P Square countdown-only styles (generated by build_launch.py from site/assets/css/style.css) */\n" + extract(css).replace("url(../fonts/", "url(fonts/")
if os.path.isdir(OUT): shutil.rmtree(OUT)
for d in ("assets/fonts", "assets/media", "assets/img"): os.makedirs(OUT + "/" + d)
open(OUT + "/index.html", "w", encoding="utf-8").write(html)
open(OUT + "/assets/countdown.js", "w", encoding="utf-8").write(js)
open(OUT + "/assets/launch.css", "w", encoding="utf-8").write(lcss)
for f in os.listdir(SITE + "/assets/fonts"): shutil.copy(SITE + "/assets/fonts/" + f, OUT + "/assets/fonts/" + f)
refs = sorted(set(re.findall(r"assets/((?:img|media)/[A-Za-z0-9_\-]+\.(?:jpg|png|mp4))", html)))
for r in refs: shutil.copy(SITE + "/assets/" + r, OUT + "/assets/" + r)
for f in ("favicon.png", "apple-touch-icon.png"): shutil.copy(SITE + "/" + f, OUT + "/" + f)
open(OUT + "/robots.txt", "w").write("User-agent: *\nDisallow: /\n")
open(OUT + "/404.html", "w", encoding="utf-8").write('<!doctype html><meta charset="utf-8"><meta name="robots" content="noindex"><meta http-equiv="refresh" content="0;url=/"><title>P Square Interior Studio</title><a href="/">P Square Interior Studio</a>')
leak = [w for w in ("preview", 'id="projects"', 'id="contact"', "main.js") if w in html + js]
assert not leak, "full-site reference in launch build: %s" % leak
print("launch/ built: launch_at=%s media=%s" % (LAUNCH or "-", refs))
